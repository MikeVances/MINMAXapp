// ─────────────────────────────────────────────────────────
//  Runtime
// ─────────────────────────────────────────────────────────
(function () {
  const lang = localStorage.getItem('lang') || 'en';
  const _t   = LOCALES[lang] || LOCALES.en;

  // Global t() — synchronous, available immediately
  window.t = function (key, vars) {
    let str = _t[key];
    if (str === undefined) str = LOCALES.en[key]; // English fallback
    if (str === undefined) str = key;              // last resort: echo key
    if (vars && typeof str === 'string') {
      str = str.replace(/\{(\w+)\}/g, (_, k) => vars[k] !== undefined ? vars[k] : `{${k}}`);
    }
    return str;
  };

  window.I18N = {
    lang,
    t: window.t,

    setLang(newLang) {
      localStorage.setItem('lang', newLang);
      location.reload();
    },

    applyDOM() {
      // data-i18n → textContent
      document.querySelectorAll('[data-i18n]').forEach(el => {
        const v = _t[el.dataset.i18n] ?? LOCALES.en[el.dataset.i18n];
        if (v !== undefined) el.textContent = v;
      });
      // data-i18n-html → innerHTML
      document.querySelectorAll('[data-i18n-html]').forEach(el => {
        const v = _t[el.dataset.i18nHtml] ?? LOCALES.en[el.dataset.i18nHtml];
        if (v !== undefined) el.innerHTML = v;
      });
      // data-i18n-placeholder → placeholder attribute
      document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const v = _t[el.dataset.i18nPlaceholder] ?? LOCALES.en[el.dataset.i18nPlaceholder];
        if (v !== undefined) el.placeholder = v;
      });
      // data-i18n-title → title attribute
      document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const v = _t[el.dataset.i18nTitle] ?? LOCALES.en[el.dataset.i18nTitle];
        if (v !== undefined) el.title = v;
      });

      document.documentElement.lang = lang;

      // Page <title> tag
      const tk = document.body && document.body.dataset.pageTitle;
      if (tk) {
        const v = _t[tk] ?? LOCALES.en[tk];
        if (v) document.title = v;
      }
    }
  };

  // Inject language-toggle button (fixed, top-right)
  function injectLangToggle() {
    const btn = document.createElement('button');
    btn.className = 'btn btn-secondary';
    btn.style.cssText = 'position:fixed;top:8px;right:8px;z-index:9999;font-size:12px;padding:4px 10px;opacity:.85;';
    btn.textContent  = lang === 'en' ? '🌐 RU' : '🌐 EN';
    btn.title        = lang === 'en' ? 'Switch to Russian' : 'Переключить на английский';
    btn.onclick      = () => I18N.setLang(lang === 'en' ? 'ru' : 'en');
    document.body.appendChild(btn);
  }

  document.addEventListener('DOMContentLoaded', () => {
    I18N.applyDOM();
    injectLangToggle();
  });
})();
