"""
Поправка уставки температуры на влажность — принцип ОЩУЩАЕМОЙ температуры.

Птица отдаёт тепло в основном испарением при дыхании. При сухом воздухе
испарение идёт легче, и птице холоднее — сухую температуру поднимают; при
влажном — опускают. Селекционеры задают это таблицей «масса × RH → T».

Источник: Aviagen, Ross Broiler Management Handbook 2025, табл. 2.5 (стр. 30),
формула Dr. Malcolm Mitchell (Scotland's Rural College). Там же оговорка:
по последним данным RH менее критична при массе 200–2500 г.

Температура в профилях роста хранится как ОПОРНАЯ при RH 60 %
(см. data/growth_profiles). Здесь считается только сдвиг относительно
60 %: так поправка работает и для пользовательских профилей, где
температуру задали под свою площадку.
"""

from __future__ import annotations

from .errors import CalcError

REFERENCE_RH = 60.0

# Колонки таблицы 2.5, % RH — за их пределами таблица ничего не утверждает.
# Сверено с PDF Handbook 2025 (стр. 30) 2026-10-19: в документе ровно 40–70 %, все
# 40 значений совпадают — таблица не обрезана (находка аудита «обрезана на 70 %» снята)
RH_COLUMNS = (40.0, 50.0, 60.0, 70.0)

# Масса, г → сухая температура, °C при RH 40 / 50 / 60 / 70 %.
# Последняя строка в документе — «>1530 г»: дальше температура постоянна.
TABLE_2_5 = (
    (44,   (36.0, 33.2, 30.8, 29.2)),
    (100,  (33.7, 31.2, 28.9, 27.3)),
    (180,  (32.5, 29.9, 27.7, 26.0)),
    (290,  (31.3, 28.6, 26.7, 25.0)),
    (425,  (30.2, 27.8, 25.7, 24.0)),
    (590,  (29.0, 26.8, 24.8, 23.0)),
    (790,  (27.7, 25.5, 23.6, 21.9)),
    (1015, (26.9, 24.7, 22.7, 21.3)),
    (1260, (25.7, 23.5, 21.7, 20.2)),
    (1530, (24.8, 22.7, 20.7, 19.3)),
)


def _row_for_weight(weight_g: float) -> tuple[float, ...]:
    """Строка таблицы для массы: линейно между соседними строками, по краям — крайняя."""
    if weight_g <= TABLE_2_5[0][0]:
        return TABLE_2_5[0][1]
    if weight_g >= TABLE_2_5[-1][0]:
        return TABLE_2_5[-1][1]
    for (w0, row0), (w1, row1) in zip(TABLE_2_5, TABLE_2_5[1:]):
        if w0 <= weight_g <= w1:
            k = (weight_g - w0) / (w1 - w0)
            return tuple(a + (b - a) * k for a, b in zip(row0, row1))
    raise AssertionError("unreachable: table is sorted by weight")


def _temp_at_rh(row: tuple[float, ...], rh: float) -> float:
    for (rh0, t0), (rh1, t1) in zip(zip(RH_COLUMNS, row), zip(RH_COLUMNS[1:], row[1:])):
        if rh0 <= rh <= rh1:
            return t0 + (t1 - t0) * (rh - rh0) / (rh1 - rh0)
    raise CalcError("rh_out_of_table", rh=rh, min=round(RH_COLUMNS[0]), max=round(RH_COLUMNS[-1]))


def rh_temperature_shift(weight_g: float, target_rh: float) -> float:
    """
    На сколько °C сдвинуть уставку, заданную при RH 60 %, для целевой RH.

    Положительный сдвиг — суше 60 %, теплее; отрицательный — влажнее, прохладнее.
    Пример: 2.3 кг при RH 70 % → 19.3 − 20.7 = −1.4 °C.
    """
    row = _row_for_weight(weight_g)
    return _temp_at_rh(row, target_rh) - _temp_at_rh(row, REFERENCE_RH)
