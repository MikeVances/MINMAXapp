"""
Имя корпуса (house_id): единые правила для всех роутеров и хранилищ.

Имя показывается в UI и попадает в имя файла на диске, поэтому:
  - допустимы только буквы (в т.ч. кириллица), цифры, пробел, точка, дефис
    и подчёркивание — без HTML-разметки (stored XSS, ревью 2026-10-16);
  - в имя файла имя переводится ОБРАТИМО: старая замена «всё лишнее → _»
    склеивала «A.1» и «A_1» в один файл, и второй корпус затирал первый.
"""

from __future__ import annotations

from urllib.parse import quote, unquote

HOUSE_ID_PATTERN = r"^[\w .\-]{1,64}$"


def house_id_to_filename(house_id: str) -> str:
    """
    Безопасный и однозначный фрагмент имени файла.

    quote() оставляет латиницу, цифры, «-», «_», «.» как есть, а пробел и
    кириллицу кодирует как %XX. Процент в имени файла безопасен, а обратное
    преобразование (unquote) восстанавливает исходное имя без потерь.
    safe="" — чтобы «/» тоже кодировался, а не создавал подкаталог.
    """
    return quote(house_id, safe="")


def filename_to_house_id(fragment: str) -> str:
    """Обратное преобразование для списка корпусов по файлам на диске."""
    return unquote(fragment)
